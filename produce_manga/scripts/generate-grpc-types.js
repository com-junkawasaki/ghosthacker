#!/usr/bin/env node
/**
 * Generate TypeScript types from proto files for gRPC-Web client
 * Uses protobufjs to load proto files and generate TypeScript definitions
 */

const fs = require('fs');
const path = require('path');
const protobuf = require('protobufjs');

const PROTO_DIR = path.join(__dirname, '../performers/services/grpc/proto');
const OUT_DIR = path.join(__dirname, '../src/lib/grpc/generated');

// Create output directory
if (!fs.existsSync(OUT_DIR)) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

async function generateTypes() {
  try {
    console.log('Loading proto files...');
    const root = await protobuf.load(path.join(PROTO_DIR, 'manga.proto'));

    // Generate TypeScript definitions
    console.log('Generating TypeScript types...');
    
    // Generate message types
    const messageTypes = [];
    const serviceTypes = [];
    const typeMap = new Map();

    // First pass: collect all types
    function collectTypes(nested, prefix = '') {
      if (nested instanceof protobuf.Type) {
        const typeName = nested.name;
        const fullName = prefix ? `${prefix}.${typeName}` : typeName;
        typeMap.set(fullName, nested);
      } else if (nested instanceof protobuf.Namespace) {
        nested.nestedArray.forEach((child) => {
          collectTypes(child, prefix ? `${prefix}.${nested.name}` : nested.name);
        });
      }
    }

    root.nestedArray.forEach((nested) => {
      collectTypes(nested);
    });

    // Second pass: generate message types
    function generateMessageType(type, prefix = '') {
      const typeName = type.name;
      const fields = type.fieldsArray.map((field) => {
        const fieldType = getTypeScriptType(field.type, field.repeated, field.map, prefix);
        // In proto3, all fields are optional unless they're repeated or have explicit optional keyword
        // Check if field has optional keyword (proto3)
        const isOptional = field.optional === true || (!field.repeated && !field.map && field.type !== 'string');
        return `  ${field.name}${isOptional ? '?' : ''}: ${fieldType};`;
      }).join('\n');

      return `export interface ${typeName} {\n${fields}\n}`;
    }

    // Process manga_editor namespace
    const mangaEditorNamespace = root.lookup('manga_editor');
    if (mangaEditorNamespace) {
      mangaEditorNamespace.nestedArray.forEach((nested) => {
        if (nested instanceof protobuf.Type) {
          messageTypes.push(generateMessageType(nested, 'manga_editor'));
        } else if (nested instanceof protobuf.Service) {
          const serviceName = nested.name;
          const methods = nested.methodsArray.map((method) => {
            const requestType = method.requestType.name;
            const responseType = method.responseType.name;
            const methodName = method.name;
            
            return `  ${methodName}(request: ${requestType}): Promise<${responseType}>;`;
          }).join('\n');

          serviceTypes.push(`export interface ${serviceName}Client {\n${methods}\n}`);
        }
      });
    } else {
      // Fallback: process root level types
      root.nestedArray.forEach((nested) => {
        if (nested instanceof protobuf.Type) {
          messageTypes.push(generateMessageType(nested));
        } else if (nested instanceof protobuf.Service) {
          const serviceName = nested.name;
          const methods = nested.methodsArray.map((method) => {
            const requestType = method.requestType.name;
            const responseType = method.responseType.name;
            const methodName = method.name;
            
            return `  ${methodName}(request: ${requestType}): Promise<${responseType}>;`;
          }).join('\n');

          serviceTypes.push(`export interface ${serviceName}Client {\n${methods}\n}`);
        }
      });
    }

    // Generate service client implementation
    const serviceClientCode = generateServiceClient(root);

    // Write generated files
    const typesContent = `/**
 * @context https://gftd.ai/ontology/manga-editor#
 * @type cpm:Resource
 * @id https://gftd.ai/resource/grpc-generated-types
 * 
 * Auto-generated TypeScript types from proto files
 * DO NOT EDIT THIS FILE MANUALLY
 * Generated from: ${PROTO_DIR}/manga.proto
 * Generated at: ${new Date().toISOString()}
 */

${messageTypes.join('\n\n')}

${serviceTypes.join('\n\n')}
`;

    fs.writeFileSync(path.join(OUT_DIR, 'types.ts'), typesContent, 'utf-8');
    fs.writeFileSync(path.join(OUT_DIR, 'client.ts'), serviceClientCode, 'utf-8');

    console.log(`✓ Generated types in ${OUT_DIR}`);
    console.log(`  - types.ts (${messageTypes.length} message types, ${serviceTypes.length} service types)`);
    console.log(`  - client.ts (service client implementation)`);
  } catch (error) {
    console.error('Error generating types:', error);
    process.exit(1);
  }
}

function getTypeScriptType(protoType, repeated, map, prefix = '') {
  if (map) {
    return `Record<string, ${getTypeScriptType(map.valueType, false, null, prefix)}>`;
  }
  if (repeated) {
    return `${getTypeScriptType(protoType, false, null, prefix)}[]`;
  }
  
  // Handle nested types
  if (protoType.includes('.')) {
    // Already fully qualified
    const parts = protoType.split('.');
    return parts[parts.length - 1];
  }
  
  switch (protoType) {
    case 'string':
      return 'string';
    case 'int32':
    case 'int64':
    case 'uint32':
    case 'uint64':
    case 'sint32':
    case 'sint64':
    case 'fixed32':
    case 'fixed64':
    case 'sfixed32':
    case 'sfixed64':
      return 'number';
    case 'float':
    case 'double':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'bytes':
      return 'string'; // Base64 encoded
    default:
      // Custom message type - check if it's in the same package
      if (prefix && protoType) {
        // Try to resolve the full name
        return protoType;
      }
      return protoType;
  }
}

function generateServiceClient(root) {
  const service = root.lookupService('manga_editor.MangaEditorService');
  if (!service) {
    throw new Error('MangaEditorService not found');
  }

  // Collect unique type names
  const typeNames = new Set();
  service.methodsArray.forEach((method) => {
    // method.requestType and method.responseType are strings (type names)
    // Resolve them to get the actual type objects
    try {
      const requestTypeName = typeof method.requestType === 'string' 
        ? method.requestType 
        : method.requestType.name;
      const responseTypeName = typeof method.responseType === 'string'
        ? method.responseType
        : method.responseType.name;
      
      // Resolve full names
      const requestType = root.lookupType(requestTypeName);
      const responseType = root.lookupType(responseTypeName);
      
      if (requestType) {
        typeNames.add(requestType.name);
      }
      if (responseType) {
        typeNames.add(responseType.name);
      }
    } catch (e) {
      console.warn(`Warning: Could not resolve types for method ${method.name}:`, e.message);
    }
  });

  const methods = service.methodsArray.map((method) => {
    // Resolve type names
    let requestType = 'unknown';
    let responseType = 'unknown';
    
    try {
      const requestTypeName = typeof method.requestType === 'string' 
        ? method.requestType 
        : method.requestType.name;
      const responseTypeName = typeof method.responseType === 'string'
        ? method.responseType
        : method.responseType.name;
      
      const requestTypeObj = root.lookupType(requestTypeName);
      const responseTypeObj = root.lookupType(responseTypeName);
      
      requestType = requestTypeObj ? requestTypeObj.name : requestTypeName.split('.').pop();
      responseType = responseTypeObj ? responseTypeObj.name : responseTypeName.split('.').pop();
    } catch (e) {
      console.warn(`Warning: Could not resolve types for method ${method.name}:`, e.message);
      // Fallback: try to extract name from string
      if (typeof method.requestType === 'string') {
        requestType = method.requestType.split('.').pop();
      }
      if (typeof method.responseType === 'string') {
        responseType = method.responseType.split('.').pop();
      }
    }
    
    const methodName = method.name;
    const serviceName = 'MangaEditorService';
    const packageName = 'manga_editor';
    const methodPath = `/${packageName}.${serviceName}/${methodName}`;

    return `
  /**
   * ${methodName}
   */
  async ${methodName}(request: types.${requestType}): Promise<types.${responseType}> {
    const method = await getMethodDef('${methodName}', '${requestType}', '${responseType}');
    return this.unaryCall(method, request);
  }`;
  }).join('\n');

  return `/**
 * @context https://gftd.ai/ontology/manga-editor#
 * @type cpm:Resource
 * @id https://gftd.ai/resource/grpc-generated-client
 * 
 * Auto-generated gRPC-Web client from proto files
 * DO NOT EDIT THIS FILE MANUALLY
 * Generated from: ${PROTO_DIR}/manga.proto
 * Generated at: ${new Date().toISOString()}
 */

import { grpcClient } from '../client';
import { grpc } from '@improbable-eng/grpc-web';
import { createMethodDefinition } from '../message-serializer';
import type * as types from './types';

// Re-export types for convenience
export type {
  ${Array.from(typeNames).join(',\n  ')}
} from './types';

// Method definitions cache
const methodDefCache = new Map<string, Promise<grpc.MethodDefinition<any, any>>>();

/**
 * Get or create method definition for gRPC-Web
 */
async function getMethodDef(
  methodName: string,
  requestTypeName: string,
  responseTypeName: string
): Promise<grpc.MethodDefinition<any, any>> {
  const cacheKey = \`\${methodName}:\${requestTypeName}:\${responseTypeName}\`;
  if (!methodDefCache.has(cacheKey)) {
    methodDefCache.set(
      cacheKey,
      createMethodDefinition('MangaEditorService', methodName, requestTypeName, responseTypeName)
    );
  }
  return methodDefCache.get(cacheKey)!;
}

export class MangaEditorServiceClient {
  constructor(private client = grpcClient) {}

  private async unaryCall<Req, Res>(
    method: grpc.MethodDefinition<Req, Res>,
    request: Req
  ): Promise<Res> {
    return this.client.unaryCall(method, request);
  }
${methods}
}

export const mangaEditorServiceClient = new MangaEditorServiceClient();
`;
}

// Run if called directly
if (require.main === module) {
  generateTypes().catch((error) => {
    console.error('Failed to generate types:', error);
    process.exit(1);
  });
}

module.exports = { generateTypes };

